  }

  splits {
    abi {
      isEnable = false
    }
  }

  signingConfigs {
    val keystorePath = System.getenv("KEYSTORE_PATH")
    if (!keystorePath.isNullOrBlank()) {
      create("release") {
        storeFile = file(keystorePath)
        storePassword = System.getenv("STORE_PASSWORD")
        keyAlias = System.getenv("KEY_ALIAS") ?: "upload"
        keyPassword = System.getenv("KEY_PASSWORD")
      }
    }
    if (file("${rootDir}/debug.keystore").exists()) {
      create("debugConfig") {
        storeFile = file("${rootDir}/debug.keystore")
        storePassword = "android"
        keyAlias = "androiddebugkey"
        keyPassword = "android"
      }
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      val keystorePath = System.getenv("KEYSTORE_PATH")
      if (!keystorePath.isNullOrBlank() && file(keystorePath).exists()) {
        signingConfig = signingConfigs.getByName("release")
      } else if (file("${rootDir}/debug.keystore").exists()) {
        signingConfig = signingConfigs.getByName("debugConfig")
      } else {
        signingConfig = signingConfigs.getByName("debug")
      }
    }
    debug {
      if (file("${rootDir}/debug.keystore").exists()) {
        signingConfig = signingConfigs.getByName("debugConfig")
      }
    }
  }
  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
  }
  buildFeatures {
    compose = true
    buildConfig = true
  }
  testOptions { unitTests { isIncludeAndroidResources = true } }
}

tasks.configureEach {
  if (name == "signReleaseBundle") {
    doFirst {
      val requiredVariables = listOf("KEYSTORE_PATH", "STORE_PASSWORD", "KEY_ALIAS", "KEY_PASSWORD")
      val missingVariables = requiredVariables.filter { System.getenv(it).isNullOrBlank() }
      if (missingVariables.isNotEmpty()) {
        throw GradleException(
          "Release signing is not configured. Set ${missingVariables.joinToString(", ")} in a protected build environment."
        )
      }
      val keystorePath = System.getenv("KEYSTORE_PATH")
      if (keystorePath != null && !File(keystorePath).isFile) {
        throw GradleException("Release keystore does not exist at KEYSTORE_PATH.")
      }
    }
  }
}


